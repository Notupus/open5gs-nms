#!/bin/bash
# generate_open5gs_systemd_fixed.sh
# Generates systemd service files for all Open5GS components
# Corrects for configs with no "open5gs-" prefix

# Map of service -> config file
declare -A service_config=(
    [open5gs-pcrfd]=pcrf.yaml
    [open5gs-amfd]=amf.yaml
    [open5gs-pcfd]=pcf.yaml
    [open5gs-nrfd]=nrf.yaml
    [open5gs-upfd]=upf.yaml
    [open5gs-udrd]=udr.yaml
    [open5gs-hssd]=hss.yaml
    [open5gs-bsfd]=bsf.yaml
    [open5gs-scpd]=scp.yaml
    [open5gs-smfd]=smf.yaml
    [open5gs-seppd]=sepp1.yaml
    [open5gs-sgwud]=sgwu.yaml
    [open5gs-ausfd]=ausf.yaml
    [open5gs-mmed]=mme.yaml
    [open5gs-sgwcd]=sgwc.yaml
    [open5gs-nssfd]=nssf.yaml
    [open5gs-udmd]=udm.yaml
)

systemd_dir="/etc/systemd/system"

echo "Generating Open5GS systemd service files in $systemd_dir"

for svc in "${!service_config[@]}"; do
    config_file="${service_config[$svc]}"
    unit_file="$systemd_dir/$svc.service"
    cat <<EOF | sudo tee "$unit_file" > /dev/null
[Unit]
Description=Open5GS $svc daemon
After=network.target

[Service]
ExecStart=/usr/bin/$svc -c /etc/open5gs/$config_file
Restart=on-failure
User=root
Group=root
LimitNOFILE=65535

[Install]
WantedBy=multi-user.target
EOF

    echo "Created $unit_file -> /etc/open5gs/$config_file"
done

# Reload systemd daemon
sudo systemctl daemon-reload

# Enable all Open5GS services
for svc in "${!service_config[@]}"; do
    sudo systemctl enable "$svc"
done

echo "All Open5GS services generated and enabled."
echo "Start individual services with: sudo systemctl start <service>"

# ── TUN interface bring-up script ─────────────────────────────────────────────
# Create /usr/local/sbin/open5gs-ogstun-up.sh which is responsible for:
#   ogstun  — default-DNN / internet (10.45.0.1/16)
#   ogstun2 — IMS DNN              (10.46.0.1/24)
# This script is called by ogstun-setup.service on every boot before the UPF
# and S-GW-U start.  The ogstun2 block is essential: RTPEngine and Kamailio
# P-CSCF both bind to 10.46.0.1, so the interface must exist before those
# services start.  Without this, rtpengine-daemon fails with:
#   "Failed to open UDP NG control connection port (10.46.0.1:2223): Bad file descriptor"

sudo mkdir -p /usr/local/sbin
sudo tee /usr/local/sbin/open5gs-ogstun-up.sh > /dev/null << 'SCRIPT'
#!/usr/bin/env bash
# open5gs-ogstun-up.sh — generated by generate_open5gs_systemd.sh
# Idempotent TUN interface setup for Open5GS (ogstun + ogstun2).
set -euo pipefail

# ── ogstun (default DNN / internet) ──────────────────────────────────────────
if ! ip link show ogstun > /dev/null 2>&1; then
    ip tuntap add name ogstun mode tun
fi

sysctl -w net.ipv6.conf.ogstun.disable_ipv6=0 > /dev/null
ip addr replace 10.45.0.1/16 dev ogstun
ip -6 addr replace 2001:db8:cafe::1/48 dev ogstun
ip link set ogstun up

iptables -t nat -C POSTROUTING -s 10.45.0.0/16 ! -o ogstun -j MASQUERADE 2>/dev/null || \
    iptables -t nat -A POSTROUTING -s 10.45.0.0/16 ! -o ogstun -j MASQUERADE
ip6tables -t nat -C POSTROUTING -s 2001:db8:cafe::/48 ! -o ogstun -j MASQUERADE 2>/dev/null || \
    ip6tables -t nat -A POSTROUTING -s 2001:db8:cafe::/48 ! -o ogstun -j MASQUERADE || true
iptables -C INPUT -i ogstun -j ACCEPT 2>/dev/null || \
    iptables -I INPUT -i ogstun -j ACCEPT
ip6tables -C INPUT -i ogstun -j ACCEPT 2>/dev/null || \
    ip6tables -I INPUT -i ogstun -j ACCEPT || true
iptables -C FORWARD -i ogstun -j ACCEPT 2>/dev/null || \
    iptables -I FORWARD -i ogstun -j ACCEPT
iptables -C FORWARD -o ogstun -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT 2>/dev/null || \
    iptables -I FORWARD -o ogstun -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT

# ── ogstun2 (IMS DNN — 10.46.0.1/24) ────────────────────────────────────────
# Required by: open5gs-upfd (UPF IMS session), rtpengine-daemon (listen-ng),
#              kamailio-pcscf (RTPEngine socket).  Must be up before those
#              services start, hence Before= in ogstun-setup.service.
if ! ip link show ogstun2 > /dev/null 2>&1; then
    ip tuntap add name ogstun2 mode tun
fi

sysctl -w net.ipv6.conf.ogstun2.disable_ipv6=0 > /dev/null 2>&1 || true
ip addr replace 10.46.0.1/24 dev ogstun2
ip link set ogstun2 up

iptables -C INPUT -i ogstun2 -j ACCEPT 2>/dev/null || \
    iptables -I INPUT -i ogstun2 -j ACCEPT
iptables -C FORWARD -i ogstun2 -j ACCEPT 2>/dev/null || \
    iptables -I FORWARD -i ogstun2 -j ACCEPT
iptables -C FORWARD -o ogstun2 -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT 2>/dev/null || \
    iptables -I FORWARD -o ogstun2 -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
SCRIPT

sudo chmod +x /usr/local/sbin/open5gs-ogstun-up.sh
echo "Installed /usr/local/sbin/open5gs-ogstun-up.sh"

# ── ogstun-setup.service ──────────────────────────────────────────────────────
sudo tee /etc/systemd/system/ogstun-setup.service > /dev/null << 'UNIT'
[Unit]
Description=Configure ogstun/ogstun2 TUN interfaces and NAT for Open5GS
After=network.target
Before=open5gs-upfd.service open5gs-sgwud.service rtpengine-daemon.service kamailio-pcscf.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/open5gs-ogstun-up.sh

[Install]
WantedBy=multi-user.target
UNIT

sudo systemctl daemon-reload
sudo systemctl enable ogstun-setup.service
echo "Installed and enabled ogstun-setup.service"
